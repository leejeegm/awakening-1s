/** 2~3음절 조합 확장 — 성능을 위해 카테고리당 상한 적용 */
function expandKeywords(base, phrases, maxPerKind = 900) {
  const out = new Set([...base, ...phrases]);
  const suffixes = [
    "이", "가", "을", "를", "은", "는", "에서", "와", "과", "도",
    "한", "스러", "스러운", "스러웠", "스러움", "감", "함",
  ];
  for (const w of base) {
    if (w.length < 3 || w.length > 10) continue;
    for (const s of suffixes) {
      out.add(w + s);
      if (out.size >= maxPerKind) break;
    }
    if (out.size >= maxPerKind) break;
  }
  return [...out].sort((a, b) => b.length - a.length);
}

